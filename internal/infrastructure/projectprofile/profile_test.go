func TestCancelledContextStopsEarlyWithoutPanicking(t *testing.T) {
	t.Parallel()
	root := makeTree(t, map[string]string{
		"tsconfig.json": `{"exclude": ["template"]}`,
		"template/x.ts": "",
		".gitignore":    "out/\n",
		"out/":          "",
	})

	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	p := projectprofile.Load(ctx, root)

	assert.NotContains(t, p.ExcludeGlobs(), "out/")
}

func TestResultIsDeterministic(t *testing.T) {
	t.Parallel()
	root := makeTree(t, map[string]string{
		"tsconfig.json": `{"exclude": ["template", "legacy"]}`,
		"template/x.ts": "",
		"legacy/y.ts":   "",
	})

	first := load(t, root)
	for range 5 {
		assert.Equal(t, first.ExcludeGlobs(), load(t, root).ExcludeGlobs())
	}
	assert.Equal(t, []string{"legacy/", "template/"}, first.ExcludeGlobs())
}
