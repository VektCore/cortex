// --- composition and reporting ---------------------------------------------

func TestComposeWithKeepsOperatorPatternsFirst(t *testing.T) {
	t.Parallel()
	root := makeTree(t, map[string]string{
		"tsconfig.json": `{"exclude": ["template"]}`,
		"template/x.ts": "",
		".gitignore":    "template/\n",
	})

	p := load(t, root)
	out := p.ComposeWith([]string{"node_modules/", "*.min.js"})

	assert.Equal(t, []string{"node_modules/", "*.min.js", "template/"}, out)
}

func TestComposeWithNeverDropsAnOperatorPattern(t *testing.T) {
	t.Parallel()
	operator := []string{"vendor/", "dist/", "*.min.js"}
	p := load(t, t.TempDir())

	assert.Equal(t, operator, p.ComposeWith(operator))
}

