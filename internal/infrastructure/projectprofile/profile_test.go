// --- package.json workspaces ------------------------------------------------

func TestWorkspacesBringTheirOwnTSConfig(t *testing.T) {
	t.Parallel()
	root := makeTree(t, map[string]string{
		"package.json":               `{"workspaces": ["packages/*"]}`,
		"packages/web/tsconfig.json": `{"exclude": ["template"]}`,
		"packages/web/template/x.ts": "",
		"packages/api/tsconfig.json": `{"exclude": ["legacy"]}`,
		"packages/api/legacy/old.ts": "",
	})

	p := load(t, root)

	assert.ElementsMatch(t, []string{"packages/web/template/", "packages/api/legacy/"}, patterns(p))
	e, ok := exclusionFor(p, "packages/web/template/")
	require.True(t, ok)
	assert.Equal(t, "packages/web/tsconfig.json", e.File)
	assert.Equal(t, []string{"packages/*"}, p.Workspaces)
}

